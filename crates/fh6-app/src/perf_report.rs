//! The Markdown report written by `--bench-seconds N` (docs/perf/engine.md).
use crate::latency::Percentiles;
use crate::render_loop::RenderSummary;
use std::fmt::Write as _;

fn row(out: &mut String, name: &str, p: &Percentiles) {
    let _ = writeln!(
        out,
        "| {name} | {:.3} | {:.3} | {:.3} | {} |",
        p.p50, p.p99, p.max, p.count
    );
}

/// Renders the benchmark summary as Markdown.
pub fn markdown(s: &RenderSummary, seconds: u64, stats_overlay: bool) -> String {
    let refresh_ms = s.refresh.as_secs_f64() * 1000.0;
    let hz = if refresh_ms > 0.0 { 1000.0 / refresh_ms } else { 0.0 };
    let secs = s.measured.as_secs_f64().max(f64::EPSILON);
    let mut out = String::with_capacity(4096);
    let _ = writeln!(out, "# Engine performance (Phase 4)\n");
    let _ = writeln!(
        out,
        "Generated by `FH6_WheelDash --bench-seconds {seconds}` while `mock-udp` streamed telemetry. \
         Regenerate with the commands at the end of this file.\n"
    );
    let _ = writeln!(out, "| Setting | Value |\n|---|---|");
    let _ = writeln!(out, "| Adapter | {} |", s.adapter);
    let _ = writeln!(out, "| Swapchain | {} x {}, {}, premultiplied alpha, frame latency 1 |", s.size.0, s.size.1, s.present_mode);
    let _ = writeln!(out, "| Display refresh (DWM) | {refresh_ms:.3} ms ({hz:.1} Hz) |");
    let _ = writeln!(out, "| Measured span | {secs:.1} s after 2 s warm-up |");
    let _ = writeln!(out, "| Frames presented | {} ({:.1} fps) |", s.frames, s.frames as f64 / secs);
    let _ = writeln!(out, "| New packets shown | {} ({:.1} per s) |", s.packets, s.packets as f64 / secs);
    let _ = writeln!(out, "| `--stats` overlay drawn | {} |\n", if stats_overlay { "yes" } else { "no" });

    let _ = writeln!(out, "| Series | p50 (ms) | p99 (ms) | max (ms) | samples |\n|---|---|---|---|---|");
    row(&mut out, "Packet receive -> `present` returned", &s.receive_to_present);
    row(&mut out, "Packet receive -> next vblank after present (est. on screen)", &s.receive_to_vblank);
    row(&mut out, "CPU per frame (build + upload + record + submit + present)", &s.cpu_frame);
    row(&mut out, "Blocked on the frame-latency wait (not CPU work)", &s.acquire_wait);

    let one_frame_ok = s.receive_to_vblank.p99 > 0.0 && f64::from(s.receive_to_vblank.p99) <= refresh_ms * 1.05;
    let cpu_ok = s.cpu_frame.p99 > 0.0 && s.cpu_frame.p99 < 1.0;
    let _ = writeln!(out, "\n## Against the targets\n");
    let _ = writeln!(
        out,
        "- Packet to screen within one display frame ({refresh_ms:.2} ms): p99 receive -> vblank {:.2} ms: **{}**",
        s.receive_to_vblank.p99,
        if one_frame_ok { "met" } else { "not met" }
    );
    let _ = writeln!(
        out,
        "- Under 1 ms CPU per frame: p99 {:.3} ms: **{}**",
        s.cpu_frame.p99,
        if cpu_ok { "met" } else { "not met" }
    );
    let _ = writeln!(
        out,
        "\nNotes:\n\
         - Times are measured with `Instant` on the render thread. \"Receive\" is when `recv_from` returned \
         on the UDP thread; \"present returned\" is when `Queue::present` returned.\n\
         - The vblank estimate adds the time from present to DWM's next vblank (`DwmGetCompositionTimingInfo`). \
         DWM composes at that vblank; scan-out of the composed frame can add up to one more refresh on some \
         display paths, which this method cannot observe.\n\
         - Only frames that showed a new packet count towards the receive series; CPU time counts every \
         presented frame."
    );
    let _ = writeln!(
        out,
        "\n## Reproduce\n\n```\ncargo build --release -p fh6-app -p mock-udp\n\
         target/release/mock-udp --scenario bmw_m4_cs --duration 40 --rate-hz 60\n\
         target/release/FH6_WheelDash --bench-seconds {seconds} --bench-out docs/perf/engine.md\n```"
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::Duration;

    #[test]
    fn report_mentions_targets_and_numbers() {
        let p = Percentiles {
            count: 100,
            total: 100,
            p50: 0.4,
            p99: 0.8,
            max: 1.2,
        };
        let s = RenderSummary {
            adapter: "Test GPU".into(),
            present_mode: "Mailbox".into(),
            size: (3840, 2160),
            measured: Duration::from_secs(20),
            frames: 1200,
            packets: 1190,
            receive_to_present: p,
            receive_to_vblank: Percentiles { p99: 9.0, ..p },
            cpu_frame: Percentiles { p99: 0.3, ..p },
            acquire_wait: p,
            refresh: Duration::from_micros(16_667),
        };
        let md = markdown(&s, 20, false);
        assert!(md.contains("3840 x 2160"));
        assert!(md.contains("Test GPU"));
        assert!(md.contains("**met**"));
        assert!(!md.contains("not met"));
    }
}
