//! The Markdown report written by `--bench-seconds N` (docs/perf/engine.md).
use crate::latency::Percentiles;
use crate::render_loop::RenderSummary;
use std::fmt::Write as _;

fn row(out: &mut String, name: &str, p: &Percentiles) {
    let _ = writeln!(
        out,
        "| {name} | {:.3} | {:.3} | {:.3} | {} |",
        p.p50, p.p99, p.max, p.count
    );
}

fn verdict(ok: bool) -> &'static str {
    if ok {
        "met"
    } else {
        "not met"
    }
}

/// Renders the benchmark summary as Markdown.
pub fn markdown(s: &RenderSummary, seconds: u64, stats_overlay: bool) -> String {
    let refresh_ms = s.refresh.as_secs_f64() * 1000.0;
    let hz = if refresh_ms > 0.0 { 1000.0 / refresh_ms } else { 0.0 };
    let secs = s.measured.as_secs_f64().max(f64::EPSILON);
    let hit_rate = if s.vsync_checked > 0 {
        100.0 * s.vsync_hits as f64 / s.vsync_checked as f64
    } else {
        0.0
    };
    let mut out = String::with_capacity(4096);
    let _ = writeln!(out, "# Live overlay performance (`--bench-seconds`)\n");
    let _ = writeln!(
        out,
        "Generated by `FH6_WheelDash --bench-seconds {seconds}` (release build) while `mock-udp` streamed \
         telemetry at 60 Hz. Regenerate with the commands at the end of this file.\n"
    );
    let _ = writeln!(out, "| Setting | Value |\n|---|---|");
    let _ = writeln!(out, "| Adapter | {} |", s.adapter);
    let _ = writeln!(
        out,
        "| Swapchain | {} x {}, {}, premultiplied alpha, frame latency 1 |",
        s.size.0, s.size.1, s.present_mode
    );
    let _ = writeln!(out, "| Display refresh (DWM) | {refresh_ms:.3} ms ({hz:.1} Hz) |");
    let _ = writeln!(out, "| Measured span | {secs:.1} s after 2 s warm-up |");
    let _ = writeln!(
        out,
        "| Frames presented | {} ({:.1} fps) |",
        s.frames,
        s.frames as f64 / secs
    );
    let _ = writeln!(
        out,
        "| New packets shown | {} ({:.1} per s) |",
        s.packets,
        s.packets as f64 / secs
    );
    let per_frame = |n: u64| n as f64 / (s.frames.max(1)) as f64;
    let _ = writeln!(
        out,
        "| Kit work per frame (mean) | {:.1} render passes, {:.1} draw calls |",
        per_frame(s.passes),
        per_frame(s.draw_calls)
    );
    let _ = writeln!(
        out,
        "| `--stats` overlay drawn | {} |\n",
        if stats_overlay { "yes" } else { "no" }
    );

    let _ = writeln!(
        out,
        "| Series | p50 (ms) | p99 (ms) | max (ms) | samples |\n|---|---|---|---|---|"
    );
    row(
        &mut out,
        "**Packet receive -> `present` returned**",
        &s.receive_to_present,
    );
    row(
        &mut out,
        "**CPU per frame** (the whole render-thread iteration, less the latency wait)",
        &s.cpu_frame,
    );
    row(
        &mut out,
        "  of which: loop checks before the build (config, telemetry, OSD, visibility, OLED care)",
        &s.before_build,
    );
    row(
        &mut out,
        "  of which: build (config, layout, signals, cluster `update`)",
        &s.build,
    );
    row(
        &mut out,
        "  of which: draw (scrim, wash, cluster `draw`, dim, OSD into the arena)",
        &s.draw,
    );
    row(&mut out, "  of which: upload + record + submit", &s.encode_submit);
    row(
        &mut out,
        "    of which: swapchain view, encoder, kit render, `finish`",
        &s.record,
    );
    row(
        &mut out,
        "      of which: kit render (pack, upload copy, pass recording)",
        &s.kit,
    );
    row(&mut out, "    of which: `Queue::submit`", &s.submit);
    row(&mut out, "  of which: `present` call", &s.present);
    row(
        &mut out,
        "  of which: after `present` (staging hand-back, checks)",
        &s.after_present,
    );
    if s.cpu_frame_dimmed.count > 0 {
        row(
            &mut out,
            "CPU per frame, idle-dimmed frames only (parked)",
            &s.cpu_frame_dimmed,
        );
    }
    row(
        &mut out,
        "Blocked on the frame-latency wait (not CPU work)",
        &s.acquire_wait,
    );
    row(
        &mut out,
        "Packet receive -> next vblank after present (est. on screen)",
        &s.receive_to_vblank,
    );

    let r2p_ok = s.receive_to_present.p99 > 0.0 && f64::from(s.receive_to_present.p99) < refresh_ms;
    let cpu_ok = s.cpu_frame.p99 > 0.0 && s.cpu_frame.p99 < 1.0;
    let _ = writeln!(out, "\n## Against the targets\n");
    let _ = writeln!(
        out,
        "- Receive-to-present under one display frame ({refresh_ms:.2} ms): p99 {:.3} ms: **{}**",
        s.receive_to_present.p99,
        verdict(r2p_ok)
    );
    let _ = writeln!(
        out,
        "- Under 1 ms CPU per frame: p99 {:.3} ms: **{}**",
        s.cpu_frame.p99,
        verdict(cpu_ok)
    );
    let _ = writeln!(
        out,
        "\nIndicative only (derived from DWM timing, not a target): {hit_rate:.1}% of new packets were presented \
         before the first vblank after they arrived ({} of {}); the rest were shown one refresh later. \
         DWM's reported vblank time can lag on a mostly idle desktop, so this estimate can read low. \
         Either way no packet ever waits behind another: there is no queue.",
        s.vsync_hits, s.vsync_checked
    );
    let _ = writeln!(
        out,
        "\nNotes:\n\
         - Times are measured with `Instant`. \"Receive\" is when `recv_from` returned on the UDP thread; \
         \"present returned\" is when `Queue::present` returned on the render thread.\n\
         - The vblank columns use DWM's composition timing (`DwmGetCompositionTimingInfo`) at present time. \
         Waiting for the vblank is not engine work: it is set by the display refresh. Scan-out of the composed \
         frame can add up to one more refresh on some display paths, which this method cannot observe.\n\
         - Only frames that showed a new packet count towards the receive series; CPU time counts every \
         presented frame.\n\
         - \"CPU per frame\" is the render thread's whole iteration for a presented frame, from its wake to \
         the end of the frame, less the frame-latency wait: the loop's checks, building the frame, drawing the \
         scrim, the cluster and the OSD into the kit's arena, the kit's render and submit, `present` and the \
         kit's staging hand-back. The rows under it are its parts; the small rest is the sample bookkeeping."
    );
    if s.cpu_frame_dimmed.count == 0 {
        let _ = writeln!(
            out,
            "- No frame was idle-dimmed. To measure a parked car, run `mock-udp --scenario parked` and a bench \
             longer than the 30 s idle wait (`--bench-seconds 60`)."
        );
    }
    // The stream outlasts the bench and its warm-up, so no frame falls back to the dyno.
    let stream = seconds + 30;
    let scenario = if s.cpu_frame_dimmed.count > 0 {
        "parked"
    } else {
        "bmw_m4_cs"
    };
    let _ = writeln!(
        out,
        "\n## Reproduce\n\n```\ncargo build --release -p fh6-app -p mock-udp\n\
         target/release/fh6-stand-in   (focused, full screen)\n\
         target/release/mock-udp --scenario {scenario} --duration {stream} --rate-hz 60\n\
         target/release/FH6_WheelDash --game-process fh6-stand-in.exe --bench-seconds {seconds} \
         --bench-out docs/perf/engine.md\n```"
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::Duration;

    #[test]
    fn report_mentions_targets_and_numbers() {
        let p = Percentiles {
            count: 100,
            total: 100,
            p50: 0.4,
            p99: 0.8,
            max: 1.2,
        };
        let s = RenderSummary {
            adapter: "Test GPU".into(),
            present_mode: "Mailbox".into(),
            size: (3840, 2160),
            measured: Duration::from_secs(20),
            frames: 1200,
            packets: 1190,
            receive_to_present: p,
            receive_to_vblank: Percentiles { p99: 9.0, ..p },
            cpu_frame: Percentiles { p99: 0.3, ..p },
            cpu_frame_dimmed: Percentiles::default(),
            acquire_wait: p,
            build: p,
            draw: p,
            encode_submit: p,
            record: p,
            kit: p,
            before_build: p,
            after_present: p,
            submit: p,
            present: p,
            passes: 13_200,
            draw_calls: 30_000,
            vsync_hits: 1000,
            vsync_checked: 1190,
            refresh: Duration::from_micros(16_667),
        };
        let md = markdown(&s, 20, false);
        assert!(md.contains("3840 x 2160"));
        assert!(md.contains("Test GPU"));
        assert!(md.contains("**met**"));
        assert!(!md.contains("not met"));
        assert!(md.contains("84.0%"));
        assert!(md.contains("Indicative only"));
        assert!(md.contains("draw (scrim"));
        assert!(md.contains("11.0 render passes, 25.0 draw calls"));
        assert!(md.contains("`Queue::submit`"));
        assert!(
            !md.contains("idle-dimmed frames only"),
            "no dimmed frames, no dimmed row"
        );
        assert!(md.contains("No frame was idle-dimmed"));
        assert!(md.contains("--scenario bmw_m4_cs --duration 50"));
        assert!(md.contains("loop checks before the build"));
        let parked = RenderSummary {
            cpu_frame_dimmed: p,
            ..s
        };
        let md = markdown(&parked, 60, false);
        assert!(md.contains("idle-dimmed frames only"));
        assert!(!md.contains("No frame was idle-dimmed"));
        assert!(md.contains("--scenario parked"));
    }
}
