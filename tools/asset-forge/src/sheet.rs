//! `assets/contact-sheet.html`: every asset grouped by set, with its thumbnail, format, colour
//! space, alpha, size, QA notes and generator. Pure HTML and CSS (no script), OLED black.
use crate::error::{io_err, Result};
use crate::ledger::{human, AssetRecord, Ledger};
use crate::paths::Paths;
use std::collections::BTreeMap;
use std::fmt::Write as _;

const ORDER: &[(&str, &str)] = &[
    ("glass", "Liquid Glass"),
    ("fluid", "Abstract fluid"),
    ("scifi", "Sci-fi & out of this world"),
    ("classic", "Classic & motorsport materials"),
    ("adas", "ADAS cars & road decals"),
    ("logos", "Logos"),
    ("fonts", "Fonts"),
];

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

/// Writes the sheet next to the ledger.
pub fn write(paths: &Paths, ledger: &Ledger) -> Result<()> {
    let mut by_set: BTreeMap<&str, Vec<&AssetRecord>> = BTreeMap::new();
    for r in ledger.records() {
        by_set.entry(r.set.as_str()).or_default().push(r);
    }
    let total: u64 = ledger.records().map(|r| r.bytes).sum();
    let count = ledger.records().count();
    let mut h = String::new();
    h.push_str(r#"<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Asset contact sheet</title>
<style>
:root{--bg:#000;--panel:#0b0d10;--line:#1c2026;--text:#e8ecf2;--dim:#8a94a3;--accent:#38bdf8}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:14px/1.45 "Titillium Web","Segoe UI",system-ui,sans-serif}
header{padding:28px 24px 8px}h1{margin:0;font-weight:600;letter-spacing:.02em}h2{margin:36px 24px 12px;font-weight:600;border-bottom:1px solid var(--line);padding-bottom:8px}
.meta{color:var(--dim)}nav{padding:0 24px;display:flex;gap:16px;flex-wrap:wrap}nav a{color:var(--accent);text-decoration:none}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(240px,1fr));gap:14px;padding:0 24px}
.card{background:var(--panel);border:1px solid var(--line);border-radius:10px;overflow:hidden;display:flex;flex-direction:column}
.thumb{aspect-ratio:4/3;display:flex;align-items:center;justify-content:center;background:#000}
.thumb.alpha{background-color:#15181d;background-image:linear-gradient(45deg,#20242b 25%,transparent 25%,transparent 75%,#20242b 75%),linear-gradient(45deg,#20242b 25%,transparent 25%,transparent 75%,#20242b 75%);background-size:16px 16px;background-position:0 0,8px 8px}
.thumb img{max-width:100%;max-height:100%;image-rendering:auto}
.body{padding:10px 12px;display:flex;flex-direction:column;gap:4px}.path{font-family:Consolas,monospace;font-size:12px;word-break:break-all}
.tags{display:flex;flex-wrap:wrap;gap:4px}.tag{font-size:11px;border:1px solid var(--line);border-radius:999px;padding:1px 8px;color:var(--dim)}
.qa{font-size:12px;color:#b9c4d2}details{font-size:12px;color:var(--dim)}summary{cursor:pointer}
@media (max-width:520px){.grid{padding:0 16px;grid-template-columns:1fr}header,nav{padding-left:16px;padding-right:16px}h2{margin-left:16px;margin-right:16px}}
</style></head><body>
"#);
    let _ = write!(
        h,
        r#"<header><h1>FH6 WheelDash · asset contact sheet</h1><p class="meta">{count} files · {} · generated by <code>cargo run -p asset-forge -- build</code>. Full ledger: <a href="ASSETS.md" style="color:var(--accent)">ASSETS.md</a></p></header><nav>"#,
        human(total)
    );
    for (key, title) in ORDER {
        if let Some(rows) = by_set.get(key) {
            let _ = write!(h, r##"<a href="#{key}">{title} ({})</a>"##, rows.len());
        }
    }
    h.push_str("</nav>\n");
    for (key, title) in ORDER {
        let Some(rows) = by_set.get(key) else { continue };
        let bytes: u64 = rows.iter().map(|r| r.bytes).sum();
        let _ = write!(h, r#"<h2 id="{key}">{title} <span class="meta">· {} files · {}</span></h2><div class="grid">"#, rows.len(), human(bytes));
        for r in rows {
            let thumb = r.thumb.strip_prefix("assets/").unwrap_or(&r.thumb);
            let file = r.path.strip_prefix("assets/").unwrap_or(&r.path);
            let alpha_cls = if r.alpha == "straight" || r.alpha == "premultiplied" { " alpha" } else { "" };
            let img_html = if thumb.is_empty() {
                format!(r#"<span class="meta">{}</span>"#, esc(&r.kind))
            } else {
                format!(r#"<img loading="lazy" src="{}" alt="{}">"#, esc(thumb), esc(&r.id))
            };
            let mut tags = vec![r.kind.clone(), r.dims.clone(), human(r.bytes), format!("{} / {}", r.colorspace, r.alpha)];
            if r.tileable {
                tags.push("tileable".into());
            }
            if let Some(f) = r.flipbook {
                tags.push(format!("flipbook {}x{} · {} f", f.cols, f.rows, f.frames));
            }
            let tags_html: String = tags.iter().map(|t| format!(r#"<span class="tag">{}</span>"#, esc(t))).collect();
            let _ = write!(
                h,
                r#"<div class="card"><a class="thumb{alpha_cls}" href="{}">{img_html}</a><div class="body"><div class="path">{}</div><div class="tags">{tags_html}</div>{}<details><summary>generator · licence · clusters</summary><div>{}</div><div>Licence: {}</div><div>For: {}</div></details></div></div>"#,
                esc(file),
                esc(file),
                if r.qa.is_empty() { String::new() } else { format!(r#"<div class="qa">{}</div>"#, esc(&r.qa)) },
                esc(&r.generator),
                esc(&r.licence),
                esc(&r.clusters)
            );
        }
        h.push_str("</div>\n");
    }
    h.push_str("</body></html>\n");
    let path = paths.assets().join("contact-sheet.html");
    std::fs::write(&path, h.as_bytes()).map_err(|e| io_err(&path, e))
}
